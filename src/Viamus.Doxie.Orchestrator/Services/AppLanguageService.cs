    public AppLanguageService(IKeyValueSettingsStore settings)
    {
        _settings = settings;
        CurrentLanguage = Normalize(settings.Get(SettingsKey));
    }

    public event Action? Changed;

    public string CurrentLanguage { get; private set; }

    public IReadOnlyDictionary<string, string> Languages => _languages;

    public string this[string key] => Translate(key);

    public string Translate(string key)
    {
        if (_translations.TryGetValue(CurrentLanguage, out var dictionary)
            && dictionary.TryGetValue(key, out var translated))
        {
            return translated;
        }

        return EnglishFallback(key);
    }

    public void SetLanguage(string language)
    {
        var normalized = Normalize(language);
        if (string.Equals(normalized, CurrentLanguage, StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        CurrentLanguage = normalized;
        _settings.Set(SettingsKey, normalized);
        Changed?.Invoke();
    }

    private string Normalize(string? language) =>
        !string.IsNullOrWhiteSpace(language) && _languages.ContainsKey(language)
            ? language
            : DefaultLanguage;

