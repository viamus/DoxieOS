const fs = require('node:fs');
const path = require('node:path');
const YAML = require('yaml');

const marker = '<!-- doxie/generated - edit the canonical .doxie catalog -->';
const managedManifest = '.doxie-managed';
const idPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/i;

function createShims({ root, list, safePath, stat, filesUnder, readText, writeIfChanged }) {
  function reconcileFolder(target, files) {
    let changed = 0;
    fs.mkdirSync(target, { recursive: true });
    for (const [relative, content] of files) {
      if (writeIfChanged(safePath(target, relative), content)) changed++;
    }
    for (const relative of filesUnder(target)) {
      if (files.has(relative)) continue;
      fs.unlinkSync(safePath(target, relative));
      changed++;
    }
    return changed;
  }

  function markedIds(directory) {
    return (readText(safePath(directory, managedManifest)) ?? '').split(/\r?\n/).map(id => id.trim()).filter(id => idPattern.test(id));
  }

  function writeManifest(directory, previous, current, suffix = '') {
    let changed = 0;
    for (const id of previous) {
      if (current.includes(id)) continue;
      const target = safePath(directory, id + suffix);
      if (stat(target)) {
        fs.rmSync(target, { recursive: !suffix, force: true });
        changed++;
      }
    }
    if (writeIfChanged(safePath(directory, managedManifest), `${current.sort().join('\n')}\n`)) changed++;
    return changed;
  }

  function mirror(root, items, filesFor, isClaudeSkill = false) {
    let changed = 0;
    const managed = [];
    const previous = new Set(markedIds(root));
    if (isClaudeSkill && stat(root)?.isDirectory()) {
      for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
        if (entry.isDirectory() && idPattern.test(entry.name) && stat(safePath(root, `${entry.name}/doxie/generated`))?.isFile()) previous.add(entry.name);
      }
    }
    for (const item of items) {
      if (!idPattern.test(item.id)) continue;
      const folder = safePath(root, item.id);
      if (stat(folder) && !previous.has(item.id)) continue;
      changed += reconcileFolder(folder, filesFor(item));
      managed.push(item.id);
    }
    return changed + writeManifest(root, previous, managed);
  }

  function skillFiles(skill, claude) {
    const files = new Map(filesUnder(skill.path).filter(relative => !['manifest.json', 'body.md'].includes(relative))
      .map(relative => [relative, fs.readFileSync(safePath(skill.path, relative))]));
    const description = String(skill.description).replace(/[\r\n]+/g, ' ').trim();
    const frontmatter = YAML.stringify({ name: skill.id, description });
    files.set('SKILL.md', `---\n${frontmatter}---\n\n${skill.body.trim()}\n`);
    if (claude) {
      const { displayName, category, requirements, modes, icon } = skill;
      files.set('orchestrator.json', `${JSON.stringify({ displayName, category, requirements, modes, icon }, null, 2)}\n`);
      files.set('doxie/generated', `# Generated by DoxieOS from .doxie/skills/${skill.id}/\n`);
    }
    return files;
  }

  function agentMirror(target, agents) {
    let changed = 0;
    const previous = markedIds(target);
    const current = [];
    for (const agent of agents) {
      if (!agent.agentPath || !idPattern.test(agent.id)) continue;
      const destination = safePath(target, `${agent.id}.md`);
      if (stat(destination) && !previous.includes(agent.id)) continue;
      if (writeIfChanged(destination, fs.readFileSync(agent.agentPath))) changed++;
      current.push(agent.id);
    }
    return changed + writeManifest(target, previous, current, '.md');
  }

  function codexIndex(target, skills, agents, workflows) {
    const lines = [marker, '', '# DoxieOS catalog', '',
      'Resolve Doxie identifiers through this catalog. Workflow agentId values refer to local Doxie skills.', '', '## Skills', ''];
    for (const skill of skills) {
      lines.push(`### /${skill.id}`, '', skill.description, '');
      for (const [id, mode] of Object.entries(skill.modes ?? {})) {
        if (!mode?.hidden) lines.push(`- \`${id}\` ${mode?.description ?? ''}`);
      }
      lines.push('');
    }
    lines.push('## Subagents', '');
    for (const agent of agents) if (agent.agentPath) lines.push(`- \`${agent.id}\` ${agent.description}`);
    lines.push('', '## Workflows', '');
    for (const workflow of workflows) {
      lines.push(`- \`${workflow.id}\` ${workflow.name} (${workflow.category}, ${workflow.trigger?.kind ?? 'manual'}${workflow.enabled ? '' : ', disabled'})`);
    }
    const content = `${lines.join('\n')}\n`;
    let changed = 0;
    for (const relative of ['.codex/AGENTS.md', 'AGENTS.md']) {
      const output = safePath(target, relative);
      const existing = readText(output);
      if (existing === null || existing.startsWith('<!-- doxie/generated')) {
        if (writeIfChanged(output, content)) changed++;
      }
    }
    return changed;
  }

  return function regenerate({ targetRoot = root } = {}) {
    const target = path.resolve(targetRoot);
    const skills = list('skills');
    const agents = list('agents');
    const libraries = list('libraries');
    const workflows = list('workflows');
    let changed = mirror(safePath(target, '.claude/skills'), skills, item => skillFiles(item, true), true);
    changed += mirror(safePath(target, '.agents/skills'), skills, item => skillFiles(item, false));
    changed += agentMirror(safePath(target, '.claude/agents'), agents);
    changed += mirror(safePath(target, '.claude/libraries'), libraries, item => new Map(filesUnder(item.path)
      .map(relative => [relative, fs.readFileSync(safePath(item.path, relative))])));
    changed += codexIndex(target, skills, agents, workflows);
    return { skills: skills.length, agents: agents.filter(agent => agent.agentPath).length, libraries: libraries.length,
      workflows: workflows.length, changed };
  };
}

module.exports = { createShims };
