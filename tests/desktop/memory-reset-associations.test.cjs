const assert = require('node:assert/strict');
const { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const { test } = require('node:test');
const { createMemoryStore } = require('../../src/desktop/memory-store.cjs');

test('clearing Brain deletes all knowledge and vectors, preserves originals/models and stays empty after restart', t => {
  const root = mkdtempSync(join(tmpdir(), 'doxie-brain-reset-'));
  let store = createMemoryStore({ root });
  t.after(() => { store.close(); rmSync(root, { recursive: true, force: true }); });
  const memory = store.remember({ title: 'Original memory', content: 'Keep evidence available.', source: { provider: 'codex', path: 'provider/memory.md' } });
  const entity = store.remember({ title: 'Entity', content: 'A shared entity.', kind: 'entity' });
  store.remember({ title: 'Settings', kind: 'parameter', parameters: { retries: 3 } });
  store.relate({ fromId: memory.id, toId: entity.id, type: 'mentions' });
  store.setEmbedding(memory.id, [1, 0], { model: 'fixture' });
  store.archive(memory.id);
  const legacy = join(root, '.memory', 'knowledge.db');
  const model = join(root, '.models', 'retained-model');
  const original = join(root, 'provider', 'memory.md');
  mkdirSync(join(root, '.models')); mkdirSync(join(root, 'provider'));
  writeFileSync(legacy, 'Legacy backup must not be reimported after reset.');
  writeFileSync(model, 'retained model'); writeFileSync(original, 'provider original');
  const cleared = store.reset();
  assert.equal(cleared.deleted.total, 3);
  assert.equal(cleared.deleted.relations, 1);
  assert.equal(store.stats().total, 0);
  assert.equal(store.stats().relations, 0);
  assert.equal(store.stats().sources, 0);
  assert.equal(store.get(memory.id), null);
  assert.deepEqual(store.graph().nodes, []);
  assert.deepEqual(store.search({ query: 'evidence' }).results, []);
  assert.deepEqual(store.getEmbeddings({ model: 'fixture' }), []);
  assert.deepEqual(store.records({ includeArchived: true, includeSuperseded: true, includeStale: true }), []);
  store.close(); store = createMemoryStore({ root });
  assert.equal(store.stats().total, 0, 'preserved SQLite backup must not resurrect knowledge');
  assert.equal(readFileSync(legacy, 'utf8'), 'Legacy backup must not be reimported after reset.');
  assert.equal(readFileSync(model, 'utf8'), 'retained model');
  assert.equal(readFileSync(original, 'utf8'), 'provider original');
  store.remember({ title: 'Fresh start', content: 'Only newly added knowledge is present.' });
  assert.equal(store.stats().total, 1);
});

test('associative exploration discovers indirect cross-domain paths as hypotheses and respects withdrawal', t => {
  const root = mkdtempSync(join(tmpdir(), 'doxie-brain-associations-'));
  const store = createMemoryStore({ root });
  t.after(() => { store.close(); rmSync(root, { recursive: true, force: true }); });
  const add = (title, kind = 'memory', parameters) => store.remember({ title, content: title, kind, ...(parameters ? { parameters } : {}) });
  const release = add('Bounded deployment retries');
  const releaseParameter = add('Retry limit', 'parameter', { attempts: 3 });
  const tea = add('Tea preparation repeat cycles');
  const teaParameter = add('Preparation repeats', 'parameter', { attempts: 2 });
  const direct = add('Direct release guide');
  store.relate({ fromId: release.id, toId: releaseParameter.id, type: 'supports' });
  store.relate({ fromId: tea.id, toId: teaParameter.id, type: 'supports' });
  store.relate({ fromId: releaseParameter.id, toId: teaParameter.id, type: 'related', weight: 0.72, inferred: true });
  store.relate({ fromId: release.id, toId: direct.id, type: 'related', weight: 0.9 });
  const found = store.associations({ nodeId: release.id });
  const association = found.results.find(item => item.id === tea.id);
  assert(association, 'an indirect parameter pattern can connect different domains');
  assert.equal(association.hypothesis, true);
  assert.equal(association.path.length, 4);
  assert.equal(association.relations[1].inferred, true);
  assert(association.reason.includes('Retry limit'));
  assert(!found.results.some(item => item.id === direct.id), 'direct neighbors remain in the regular graph');
  assert(Buffer.byteLength(JSON.stringify(store.associations({ nodeId: release.id, maxBytes: 1024 }))) <= 1024);
  store.review({ id: tea.id, status: 'stale', evidence: 'Needs review.' });
  assert(!store.associations({ nodeId: release.id }).results.some(item => item.id === tea.id));
  assert(store.associations({ nodeId: release.id, includeStale: true }).results.some(item => item.id === tea.id));
  store.archive(tea.id);
  assert(!store.associations({ nodeId: release.id, includeStale: true }).results.some(item => item.id === tea.id));
});
